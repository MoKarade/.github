# Contrôle « gestes de Marc à jour » (tâche .github#478, choix « Signaler et retirer » de Marc, fil Gestes, 22/10/2026) : des issues `qui:marc`
# traînaient après un geste fait ou périmé, et deux listes s'écrivaient à la main. Aucun appel d'API de plus, aucun coût IA : tout vient du relevé.
# Cinq contrôles (détail : docs/archive/cycle-de-vie-tache-2026-10-29.md §13) : « fait » clair de Marc (étiquette retirée, même commentaire que le bouton « Fait »),
# « fait » ambigu (signalé, jamais retiré), `Attend` vers une issue fermée ou introuvable, `qui:marc` avec `preuve-attendue` ou `bloqué`,
# sept jours sans activité ; plus les deux listes générées. Fonctions pures d'un côté, écritures de l'autre (`retirer`, avec `appliquer` injecté).
import datetime, re, unicodedata

SANS_ACTIVITE_J = 7
RETRAITS_PAR_TOUR = 5     # borne : un tour qui retirerait plus d'étiquettes que cela s'est trompé de cible, le reste attend le tour suivant

# Ce qui n'est pas de Marc, même écrit depuis son compte : les commentaires de Claude (pied de page), le bouton « Fait » de la page, les « Geste : ».
CLAUDE = re.compile(r'Generated by \[Claude Code\]|claude\.ai/code', re.I)
BOUTON = re.compile(r'^\s*\*\*\s*(?:Fait|Réponse de Marc|Accept[ée]e)\s*\*\*|^\s*\**\s*Geste\s*\**\s*:', re.I)

# « fait » clair = TOUS les mots viennent de cette liste et il y en a un qui dit que c'est fait. Un mot inconnu (pas, non, si, demain…) rend ambigu.
MOTS_FAIT = {'fait', 'faite', 'ok', 'okay', 'done', 'termine', 'terminee', 'fini', 'finie', 'regle', 'reglee', 'pose', 'posee', 'applique', 'appliquee', 'voila'}
MOTS_PERMIS = MOTS_FAIT | {'oui', 'c', 'est', 'j', 'ai', 'je', 'l', 'ca', 'bon', 'merci', 'tout', 'deja', 'maintenant', 'bien', 'cest'}


def _mots(texte):
    t = unicodedata.normalize('NFD', (texte or '').lower())
    t = ''.join(c for c in t if unicodedata.category(c) != 'Mn')
    return re.findall(r"[a-z0-9]+", t)


def fait_clair(texte):
    """Vrai seulement pour un « fait » sans doute possible. Pure. Une question, une négation ou un mot hors liste ne passent jamais."""
    if not texte or '?' in texte or len(texte) > 80: return False
    mots = _mots(texte)
    return bool(mots) and all(m in MOTS_PERMIS for m in mots) and any(m in MOTS_FAIT for m in mots)


def fait_ambigu(texte):
    """Parle d'un « fait » mais pas assez clairement pour retirer l'étiquette (« pas encore fait », « fait ? », « ok mais… »). Pure."""
    return not fait_clair(texte) and any(m in MOTS_FAIT for m in _mots(texte))


def est_de_marc(c):
    """Un commentaire de l'API GitHub écrit par Marc : son compte, ni le pied de page de Claude, ni le bouton « Fait », ni un « Geste : ». Pure."""
    u = c.get('user') or {}
    corps = c.get('body') or ''
    return (u.get('type') == 'User' and c.get('author_association') == 'OWNER' and 'jules' not in (u.get('login') or '').lower()
            and not CLAUDE.search(corps) and not BOUTON.match(corps))


def commentaires_de_marc(commentaires, n=3):
    """Les derniers commentaires de Marc, au format léger gardé dans le relevé (`marc_com`) : date, adresse, début du texte. Pure."""
    mes = [c for c in commentaires if est_de_marc(c)][-n:]
    return [{'c': c.get('created_at'), 'u': c.get('html_url'), 't': re.sub(r'\s+', ' ', c.get('body') or '').strip()[:120]} for c in mes]


def _t(iso):
    return datetime.datetime.fromisoformat(iso.replace('Z', '+00:00')) if iso else None


def verdict_fait(n):
    """('clair'|'ambigu'|None, commentaire) : le DERNIER commentaire de Marc, s'il est plus récent que la dernière pose de `qui:marc`. Pure."""
    depuis, coms = _t(n.get('marc_depuis')), n.get('marc_com') or []
    if not coms: return None, None
    dernier = coms[-1]
    if depuis and _t(dernier.get('c')) and _t(dernier['c']) <= depuis: return None, None
    if fait_clair(dernier.get('t')): return 'clair', dernier
    if fait_ambigu(dernier.get('t')): return 'ambigu', dernier
    return None, None


def controler(repos, maintenant):
    """repos : `repos` du relevé (backlog.json). Rend {'ouverts', 'signales', 'codes', 'gestes', 'a_retirer'}. Pure.
    Un geste = une tâche ouverte `qui:marc`. `actionnable` : Marc peut le faire maintenant (aucune attente ouverte, aucune étiquette contradictoire)."""
    ref_de = {f"{r['repo'].lower()}#{n['n']}": n for r in repos for n in r['nodes'].values()}
    gestes, a_retirer, codes = [], [], {}
    for r in repos:
        for n in r['nodes'].values():
            if n['lvl'] != 'tâche' or n['state'] != 'open' or 'qui:marc' not in n['labels']: continue
            ref = f"{r['repo']}#{n['n']}"
            signes, attend_ouvert = [], []
            verdict, com = verdict_fait(n)
            if verdict == 'clair':
                signes.append({'code': 'fait-clair', 'm': f"commentaire de Marc du {com['c'][:10]} : « {com['t']} »", 'u': com['u']})
                a_retirer.append({'ref': ref, 'depot': r['repo'], 'n': n['n'], 'quand': com['c'], 'u': com['u']})
            elif verdict == 'ambigu':
                signes.append({'code': 'fait-ambigu', 'm': f"commentaire de Marc du {com['c'][:10]} : « {com['t']} » (rien retiré)", 'u': com['u']})
            for d in n.get('deps') or []:
                cible = ref_de.get(d)
                if cible is None: signes.append({'code': 'attend-introuvable', 'm': f'la ligne Attend vise {d}, introuvable'})
                elif cible['state'] == 'closed': signes.append({'code': 'attend-ferme', 'm': f'la ligne Attend vise {d}, fermée : le geste est peut-être faisable ou périmé'})
                else: attend_ouvert.append(d)
            contradiction = sorted({'preuve-attendue', 'bloqué'} & set(n['labels']))
            if contradiction: signes.append({'code': 'etiquettes-contradictoires', 'm': 'qui:marc avec ' + ' et '.join(contradiction)})
            actif = _t(n.get('upd')) or _t(n.get('marc_depuis')) or _t(n['created'])
            inactif_j = (maintenant - actif).days if actif else 0
            if inactif_j >= SANS_ACTIVITE_J: signes.append({'code': 'sans-activite', 'm': f'aucune activité depuis {inactif_j} jours'})
            for s in signes: codes[s['code']] = codes.get(s['code'], 0) + 1
            depuis = n.get('marc_depuis') or n['created']
            gestes.append({'ref': ref, 't': n['title'], 'u': n['url'], 'depuis': depuis, 'jours': (maintenant - _t(depuis)).days,
                           'geste': (n.get('geste') or {}).get('t'), 'signes': signes, 'attend': attend_ouvert,
                           'actionnable': not attend_ouvert and not contradiction and not any(s['code'] == 'attend-introuvable' for s in signes)})
    gestes.sort(key=lambda g: g['depuis'])
    return {'ouverts': len(gestes), 'signales': sum(1 for g in gestes if g['signes']), 'codes': codes, 'gestes': gestes, 'a_retirer': a_retirer}


def _ligne(g):
    reste = f" Geste : {g['geste']}" if g.get('geste') else ''
    return f"- [{g['ref']}]({g['u']}) — {g['t']} — depuis {g['jours']} j.{reste}"


def listes_md(res, maintenant):
    """Les deux listes, générées (jamais écrites à la main). Rend (gestes_de_marc, a_faire_maintenant). Pure."""
    from reponses import heure_quebec
    h = heure_quebec(maintenant)
    pied = f"_Généré par le relevé du Gantt le {h} (heure du Québec) à partir des tâches ouvertes `qui:marc`. Ne pas modifier à la main : la prochaine génération l'efface._\n"
    ges = res['gestes']
    faisables = [g for g in ges if g['actionnable']]
    attente = [g for g in ges if not g['actionnable']]
    a = ['# À faire maintenant', '', pied, f"{len(faisables)} geste(s) que tu peux faire tout de suite.", '']
    a += [_ligne(g) for g in faisables] or ['Rien : aucun geste ne t\'attend.']
    d = ['# Gestes de Marc', '', pied, f"{res['ouverts']} geste(s) ouvert(s), {res['signales']} signalé(s).", '', '## Faisables maintenant', '']
    d += [_ligne(g) for g in faisables] or ['Aucun.']
    d += ['', '## En attente d\'autre chose', '']
    d += [_ligne(g) + (' — attend ' + ', '.join(g['attend']) if g['attend'] else ' — étiquettes ou ligne Attend à corriger') for g in attente] or ['Aucun.']
    d += ['', '## À vérifier', '']
    d += [f"- [{g['ref']}]({g['u']}) : " + ' ; '.join(s['m'] for s in g['signes']) for g in ges if g['signes']] or ['Rien à signaler.']
    return '\n'.join(d) + '\n', '\n'.join(a) + '\n'


def retirer(a_retirer, appliquer, maintenant):
    """Retire `qui:marc` sur chaque « fait » clair : `appliquer(demande, maintenant)` rend (ok, message) (reponses.appliquer). Rend (retirees, refus).
    Au plus RETRAITS_PAR_TOUR par tour ; un refus (la tâche n'attend plus Marc, déjà fermée…) se dit, il n'est pas une erreur."""
    retirees, refus = [], []
    for c in a_retirer[:RETRAITS_PAR_TOUR]:
        dem = {'depot': c['depot'], 'n': c['n'], 'geste': 'fait', 'origine': {'u': c['u'], 'c': c['quand']}}
        try: ok, msg = appliquer(dem, maintenant)
        except Exception as e: ok, msg = False, f'{type(e).__name__} : {str(e)[:120]}'
        (retirees if ok else refus).append(c['ref'] if ok else f"{c['ref']} ({msg})")
    return retirees, refus


def resume(res, retirees=(), refus=()):
    """La ligne de etat.json et sa clé structurée `gestes`. Pure."""
    morceaux = [f"{res['ouverts']} ouvert(s)", f"{res['signales']} signalé(s)"]
    if res['codes']: morceaux.append(', '.join(f'{k} {v}' for k, v in sorted(res['codes'].items())))
    if retirees: morceaux.append('retiré : ' + ', '.join(retirees))
    if refus: morceaux.append('non retiré : ' + ', '.join(refus))
    return 'gestes : ' + ' · '.join(morceaux), {'ouverts': res['ouverts'], 'signales': res['signales'], 'codes': res['codes'],
                                                'retires': list(retirees), 'refus': list(refus), 'signalements': [{'ref': g['ref'], 'codes': [s['code'] for s in g['signes']]} for g in res['gestes'] if g['signes']]}
