import datetime, unittest
import gestes as G
import reponses as R

UTC = datetime.timezone.utc
NOW = datetime.datetime(2026, 10, 23, 12, 0, tzinfo=UTC)
POSE = '2026-10-22T10:00:00Z'


def com(texte, quand='2026-10-22T15:00:00Z', **k):
    c = {'body': texte, 'created_at': quand, 'html_url': 'https://github.com/MoKarade/X/issues/1#issuecomment-1', 'author_association': 'OWNER',
         'user': {'login': 'MoKarade', 'type': 'User'}}
    c.update(k)
    return c


def noeud(n, labels=('qui:marc',), state='open', deps=(), marc_com=None, upd='2026-10-22T12:00:00Z', lvl='tâche', depuis=POSE):
    return {'n': n, 'title': f'Tâche {n}', 'lvl': lvl, 'labels': ['niveau:' + lvl, *labels], 'state': state, 'created': '2026-10-15T10:00:00Z',
            'url': f'https://github.com/MoKarade/X/issues/{n}', 'deps': list(deps), 'upd': upd, 'marc_depuis': depuis if 'qui:marc' in labels else None,
            'marc_com': marc_com if marc_com is not None else [], 'geste': {'t': f'faire {n}', 'u': 'u'}}


def repos(*ns):
    return [{'repo': 'X', 'key': 'x', 'name': 'X', 'nodes': {str(n['n']): n for n in ns}}]


def mc(texte, quand='2026-10-22T15:00:00Z'):
    return {'c': quand, 'u': 'https://github.com/MoKarade/X/issues/1#issuecomment-1', 't': texte}


class FaitClair(unittest.TestCase):
    def test_clairs(self):
        for t in ('fait', 'Fait !', "C'est fait", 'ok', 'OK, fait.', "j'ai fait", 'oui c\'est fait merci', 'done', 'Terminé', 'Fait, merci'):
            self.assertTrue(G.fait_clair(t), t)

    def test_ambigus_ne_retirent_rien(self):
        for t in ('pas encore fait', "c'est fait ?", 'je le fais demain', 'ok mais il manque la clé', 'non', 'pas fait', 'fait? non', 'ok, je regarde ça demain',
                  'ce n\'est pas fait', 'fait pour la moitié', '', None, 'x' * 100):
            self.assertFalse(G.fait_clair(t), t)

    def test_ambigu_seulement_si_on_parle_de_fait(self):
        self.assertTrue(G.fait_ambigu('pas encore fait'))
        self.assertTrue(G.fait_ambigu("c'est fait ?"))
        self.assertFalse(G.fait_ambigu('merci'))
        self.assertFalse(G.fait_ambigu('je regarde demain'))
        self.assertFalse(G.fait_ambigu('fait'))


class DeMarc(unittest.TestCase):
    def test_marc(self):
        self.assertTrue(G.est_de_marc(com('fait')))

    def test_pas_marc(self):
        self.assertFalse(G.est_de_marc(com('fait\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_')))
        self.assertFalse(G.est_de_marc(com('**Fait** — Marc, depuis la page de suivi (22/10 10:00, heure du Québec).')))
        self.assertFalse(G.est_de_marc(com('Geste : ouvre la page Profil')))
        self.assertFalse(G.est_de_marc(com('fait', author_association='CONTRIBUTOR')))
        self.assertFalse(G.est_de_marc(com('fait', user={'login': 'github-actions[bot]', 'type': 'Bot'})))
        self.assertFalse(G.est_de_marc(com('fait', user={'login': 'google-labs-jules', 'type': 'User'})))

    def test_garde_les_trois_derniers(self):
        cs = [com(f'c{i}', quand=f'2026-10-22T1{i}:00:00Z') for i in range(5)] + [com('fait\n_Generated by [Claude Code](x)_')]
        r = G.commentaires_de_marc(cs)
        self.assertEqual([c['t'] for c in r], ['c2', 'c3', 'c4'])
        self.assertEqual(set(r[0]), {'c', 'u', 't'})


class Controler(unittest.TestCase):
    def test_fait_clair_recent_est_a_retirer(self):
        r = G.controler(repos(noeud(1, marc_com=[mc('fait')])), NOW)
        self.assertEqual([c['ref'] for c in r['a_retirer']], ['X#1'])
        self.assertEqual(r['a_retirer'][0]['n'], 1)
        self.assertEqual(r['codes'], {'fait-clair': 1})

    def test_fait_plus_ancien_que_la_pose_ne_compte_pas(self):
        r = G.controler(repos(noeud(1, marc_com=[mc('fait', quand='2026-10-21T08:00:00Z')])), NOW)
        self.assertEqual(r['a_retirer'], [])
        self.assertEqual(r['codes'], {})

    def test_fait_ambigu_signale_sans_retirer(self):
        for t in ('pas encore fait', "c'est fait ?", 'ok mais il reste la clé'):
            r = G.controler(repos(noeud(1, marc_com=[mc(t)])), NOW)
            self.assertEqual(r['a_retirer'], [], t)
            self.assertEqual(r['codes'], {'fait-ambigu': 1}, t)

    def test_seul_le_dernier_commentaire_decide(self):
        r = G.controler(repos(noeud(1, marc_com=[mc('fait', '2026-10-22T14:00:00Z'), mc('non attends, pas encore fait', '2026-10-22T16:00:00Z')])), NOW)
        self.assertEqual(r['a_retirer'], [])

    def test_attend_ferme_et_introuvable(self):
        fermee = noeud(2, labels=(), state='closed')
        r = G.controler(repos(noeud(1, deps=('x#2', 'x#99')), fermee), NOW)
        self.assertEqual(r['codes'], {'attend-ferme': 1, 'attend-introuvable': 1})
        self.assertFalse(r['gestes'][0]['actionnable'])      # une cible introuvable : la ligne est à corriger avant de demander le geste

    def test_attend_ouvert_nest_pas_un_signalement_mais_un_geste_en_attente(self):
        r = G.controler(repos(noeud(1, deps=('x#2',)), noeud(2, labels=('en-cours',))), NOW)
        self.assertEqual(r['codes'], {})
        self.assertFalse(r['gestes'][0]['actionnable'])
        self.assertEqual(r['gestes'][0]['attend'], ['x#2'])

    def test_etiquettes_contradictoires(self):
        for autre in ('preuve-attendue', 'bloqué'):
            r = G.controler(repos(noeud(1, labels=('qui:marc', autre))), NOW)
            self.assertEqual(r['codes'], {'etiquettes-contradictoires': 1}, autre)
            self.assertFalse(r['gestes'][0]['actionnable'])

    def test_sept_jours_sans_activite(self):
        self.assertEqual(G.controler(repos(noeud(1, upd='2026-10-16T12:00:00Z')), NOW)['codes'], {'sans-activite': 1})
        self.assertEqual(G.controler(repos(noeud(1, upd='2026-10-16T12:01:00Z')), NOW)['codes'], {})      # 6 j 23 h 59 : pas encore

    def test_ignore_ce_qui_nest_pas_un_geste_ouvert(self):
        r = G.controler(repos(noeud(1, state='closed'), noeud(2, labels=()), noeud(3, lvl='mission')), NOW)
        self.assertEqual(r['ouverts'], 0)
        self.assertEqual(r['gestes'], [])

    def test_geste_propre(self):
        r = G.controler(repos(noeud(1)), NOW)
        self.assertEqual((r['ouverts'], r['signales']), (1, 0))
        g = r['gestes'][0]
        self.assertTrue(g['actionnable'])
        self.assertEqual((g['ref'], g['geste'], g['jours']), ('X#1', 'faire 1', 1))


class Listes(unittest.TestCase):
    def test_les_listes_sortent_de_la_requete(self):
        res = G.controler(repos(noeud(1), noeud(2, deps=('x#3',)), noeud(3, labels=('en-cours',)), noeud(4, labels=('qui:marc', 'bloqué')),
                                noeud(5, state='closed'), noeud(6, labels=())), NOW)
        gestes_md, a_faire_md = G.listes_md(res, NOW)
        for n in (1, 2, 4): self.assertIn(f'X#{n}', gestes_md)
        for n in (3, 5, 6): self.assertNotIn(f'X#{n}]', gestes_md)       # pas qui:marc ouvert : absente de la liste
        self.assertIn('X#1', a_faire_md)
        for n in (2, 4): self.assertNotIn(f'X#{n}', a_faire_md)           # en attente ou contradictoire : pas faisable maintenant
        self.assertIn('Ne pas modifier à la main', gestes_md)
        self.assertIn('3 geste(s) ouvert(s), 1 signalé(s)', gestes_md)

    def test_aucun_geste(self):
        _, a_faire = G.listes_md(G.controler(repos(noeud(1, labels=())), NOW), NOW)
        self.assertIn('Rien', a_faire)


class Retirer(unittest.TestCase):
    def test_demande_fait_avec_origine(self):
        appels = []
        def appliquer(dem, now): appels.append(dem); return True, 'appliqué'
        cand = [{'ref': 'X#1', 'depot': 'X', 'n': 1, 'quand': '2026-10-22T15:00:00Z', 'u': 'https://github.com/MoKarade/X/issues/1#issuecomment-1'}]
        self.assertEqual(G.retirer(cand, appliquer, NOW), (['X#1'], []))
        self.assertEqual(appels[0]['geste'], 'fait')
        self.assertEqual(appels[0]['origine']['u'], cand[0]['u'])

    def test_refus_et_exception_se_disent(self):
        def appliquer(dem, now):
            if dem['n'] == 2: raise RuntimeError('réseau')
            return (dem['n'] == 1), 'la tâche n\'attend plus Marc'
        cand = [{'ref': f'X#{i}', 'depot': 'X', 'n': i, 'quand': '2026-10-22T15:00:00Z', 'u': 'u'} for i in (1, 2, 3)]
        ok, refus = G.retirer(cand, appliquer, NOW)
        self.assertEqual(ok, ['X#1'])
        self.assertEqual(len(refus), 2)
        self.assertIn('RuntimeError', refus[0])
        self.assertIn("n'attend plus Marc", refus[1])

    def test_borne_par_tour(self):
        vus = []
        cand = [{'ref': f'X#{i}', 'depot': 'X', 'n': i, 'quand': '2026-10-22T15:00:00Z', 'u': 'u'} for i in range(12)]
        G.retirer(cand, lambda d, n: (vus.append(d['n']) or True, 'ok'), NOW)
        self.assertEqual(len(vus), G.RETRAITS_PAR_TOUR)


class PlanReponses(unittest.TestCase):
    ISSUE = {'state': 'open', 'labels': [{'name': 'qui:marc'}], 'title': 'Geste', 'body': ''}

    def test_commentaire_dit_son_origine_et_retire_l_etiquette(self):
        dem = {'depot': 'X', 'n': 1, 'geste': 'fait', 'origine': {'u': 'https://github.com/MoKarade/X/issues/1#issuecomment-1', 'c': '2026-10-22T15:00:00Z'}}
        actions, err = R.plan(dem, self.ISSUE, NOW)
        self.assertIsNone(err)
        self.assertEqual(actions[1], ('retirer', 'qui:marc'))
        self.assertTrue(actions[0][1].startswith('**Fait** — Marc, depuis son commentaire du '))
        self.assertIn('issuecomment-1', actions[0][1])

    def test_sans_origine_le_bouton_reste_comme_avant(self):
        actions, err = R.plan({'depot': 'X', 'n': 1, 'geste': 'fait'}, self.ISSUE, NOW)
        self.assertIn('depuis la page de suivi', actions[0][1])

    def test_deja_retiree_refuse(self):
        _, err = R.plan({'depot': 'X', 'n': 1, 'geste': 'fait', 'origine': {'u': 'u', 'c': '2026-10-22T15:00:00Z'}}, {**self.ISSUE, 'labels': []}, NOW)
        self.assertEqual(err, "la tâche n'attend plus Marc")


class Resume(unittest.TestCase):
    def test_ligne_et_cle_structuree(self):
        res = G.controler(repos(noeud(1, marc_com=[mc('fait')]), noeud(2, labels=('qui:marc', 'bloqué'))), NOW)
        ligne, cle = G.resume(res, ['X#1'], [])
        self.assertIn('2 ouvert(s) · 2 signalé(s)', ligne)
        self.assertIn('retiré : X#1', ligne)
        self.assertEqual(cle['retires'], ['X#1'])
        self.assertEqual(sorted(s['ref'] for s in cle['signalements']), ['X#1', 'X#2'])


